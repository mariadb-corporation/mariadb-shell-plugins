    def __init__(self, input=None, output: TextIO = sys.stdout):
        super().__init__(input, output)
        self.checkVersion("4.13.1")
        self._interp = LexerATNSimulator(
            self, self.atn, self.decisionsToDFA, PredictionContextCache()
        )
        self._actions = None
        self._predicates = None

    def sempred(self, localctx: RuleContext, ruleIndex: int, predIndex: int):
        if self._predicates is None:
            preds = dict()
            preds[241] = self.DOUBLE_QUOTED_TEXT_sempred
            preds[242] = self.SINGLE_QUOTED_TEXT_sempred
            self._predicates = preds
        pred = self._predicates.get(ruleIndex, None)
        if pred is not None:
            return pred(localctx, predIndex)
        else:
            raise Exception("No registered predicate for:" + str(ruleIndex))

    def DOUBLE_QUOTED_TEXT_sempred(self, localctx: RuleContext, predIndex: int):
        if predIndex == 0:
            return not self.isSqlModeActive(
                "NO_BACKSLASH_ESCAPES"
            ) and not self.isSqlModeActive("ANSI_QUOTES")

    def SINGLE_QUOTED_TEXT_sempred(self, localctx: RuleContext, predIndex: int):
        if predIndex == 1:
            return not self.isSqlModeActive("NO_BACKSLASH_ESCAPES")
